#!/usr/bin/env python3
"""Builds staging/strings.js from i18n/<lang>.json: the TV's copy in the
app's languages (`window.NIPA_STRINGS`). English lives in the page itself
(the fallback when this file or a key is missing).

Checks every language has exactly the page's English keys and keeps each
`{placeholder}`. Run from the repo root after editing i18n/ or the English
copy in staging/index.html.

    python3 tools/build_strings.py [--check]

--check: only verify that staging/strings.js is up to date (CI, test/run.sh).
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PAGE = ROOT / 'staging' / 'index.html'
OUT = ROOT / 'staging' / 'strings.js'


def english() -> dict:
    html = PAGE.read_text(encoding='utf-8')
    block = html[html.index('const STRINGS = Object.assign({'):]
    block = block[block.index('en: {') + 5:block.index('            },')]
    keys = {}
    for m in re.finditer(r'^\s+([A-Za-z]+): ("(?:[^"\\]|\\.)*"),$', block, re.M):
        keys[m.group(1)] = json.loads(m.group(2))
    assert keys, 'no English copy found in the page'
    return keys


def build() -> str:
    en = english()
    langs = {}
    for path in sorted((ROOT / 'i18n').glob('*.json')):
        lang = path.stem
        if lang == 'en':
            continue
        data = json.loads(path.read_text(encoding='utf-8'))
        missing, extra = set(en) - set(data), set(data) - set(en)
        assert not missing and not extra, (lang, sorted(missing), sorted(extra))
        for key, text in en.items():
            for ph in re.findall(r'\{\w+\}', text):
                assert ph in data[key], (lang, key, ph)
            assert data[key].strip(), (lang, key)
        langs[lang] = {k: data[k] for k in en}
    body = json.dumps(langs, ensure_ascii=False, indent=1)
    return ('// Generated by tools/build_strings.py from i18n/*.json. Do not edit.\n'
            f'window.NIPA_STRINGS = {body};\n')


def main() -> None:
    out = build()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != out:
            sys.exit('staging/strings.js is out of date: run tools/build_strings.py')
        print('strings.js up to date')
        return
    OUT.write_text(out, encoding='utf-8')
    print(f'wrote {OUT.relative_to(ROOT)}: {out.count(chr(10))} lines')


if __name__ == '__main__':
    main()
